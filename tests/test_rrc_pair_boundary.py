"""CI must retain a rejected numerical boundary, not label the candidate accepted."""

import importlib
import json
import os
from pathlib import Path
from types import SimpleNamespace


def test_development_boundary_remains_rejected_with_independent_input_control(
    tmp_path, monkeypatch
):
    root = Path(__file__).resolve().parents[1]
    monkeypatch.chdir(root)
    monkeypatch.syspath_prepend(str(root / "scripts"))
    audit = importlib.import_module("audit_rrc_word")
    diagnostic = importlib.import_module("diagnose_rrc_quantization")
    out = Path(os.environ.get("SPARKLINK_TEST_DIAGNOSTICS", str(tmp_path))) / "rrc-pair"
    out.mkdir(parents=True, exist_ok=False)
    budget = out / "budget.json"
    # Frozen RX-C2A2 development recipe; no held-out data is generated by CI.
    budget.write_text(
        json.dumps(
            dict(
                development_seed=470117,
                held_seed=480117,
                numerical_budget=dict(
                    global_normalized_rms=0.002,
                    global_relative_peak=0.02,
                    local64_relative_rms=0.02,
                ),
            )
        )
    )
    args = SimpleNamespace(
        output=out / "inputs",
        budget=budget,
        generate="development",
        selection=None,
        cost_lineage=None,
        inputs=out / "inputs",
        input_bits=12,
        coefficient_bits=16,
        model="pair",
        cycle=False,
    )
    audit.generate(args)
    args.output = out / "result"
    assert audit.evaluate(args) == 1
    summary = json.loads((args.output / "summary.json").read_text())
    assert summary["cases"] == 24 and summary["range_events"] == 0
    assert not summary["numerical_budget_passed"]
    assert not summary["local_window_acceptance"] and not summary["receiver_promotion"]
    assert summary["cycles"] is None and summary["resource_estimate"] is None
    failures = json.loads((args.output / "failures.json").read_text())
    assert failures and all(r["input"]["sha256"] for r in failures)
    assert diagnostic.diagnose(args.output, budget, out / "diagnosis") == 1
    diagnosis = json.loads((out / "diagnosis" / "diagnosis.json").read_text())
    assert diagnosis["relative_rms"]["input_only"] > 0.02
    assert diagnosis["relative_rms"]["coefficient_only"] < 0.02
