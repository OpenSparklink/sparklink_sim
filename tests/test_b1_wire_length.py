"""SHA-frozen pre-fix independent length vectors → aligned and unknown-IQ MAC.

Original uncoded data CRC was generated by an independent scalar recurrence.
These isolate length semantics; they are not full waveform/profile conformance.
All payload bytes are unchanged. Receiver selection is blind to this reference.
"""

import hashlib
import json
from dataclasses import replace
from pathlib import Path

import numpy as np
import pytest

from nearlink_sdr.phy.control_info import ControlInfoB1
from nearlink_sdr.phy.mac_interface import MacStreamReceiver, mac_to_iq
from nearlink_sdr.phy.strict_rx import PSKReceiveProfile, decode_psk_frame
from nearlink_sdr.phy.tx_pipeline import TxConfig, encode_head, tx_chain
from tests.test_psk_field_layout import independent_wire
from tests.test_rx_timing_audit import audit

ROOT = Path(__file__).parent / "data/b1-wire-length"
BASELINE = json.loads((ROOT / "baseline.json").read_text())


def profile(ft, width=24):
    return PSKReceiveProfile.ordinary(TxConfig(
        frame_type=ft, mcs_index=8, ctrl_bits_len=28 if ft == 2 else 27,
        head_llid=0x173925 if ft >= 3 else None, whitening_seed=0, crc_len=width,
        crc_seed=0x123456, pilot_interval=8, symbol_rate_mhz=4))


def receive(p, iq, quiet, chunks):
    rx = MacStreamReceiver(p, quiet)
    results, pos, j = [], 0, 0
    while pos < len(iq):
        n = chunks[j % len(chunks)]
        results.append(rx.feed(iq[pos:pos + n]))
        pos += n
        j += 1
    results.append(rx.finish())
    packets = [a.mac_payload for r in results for a in r.packets]
    events = [e for r in results for e in r.diagnostics["events"]]
    return packets, events, rx


@pytest.mark.parametrize("row", BASELINE["rows"],
                         ids=lambda r: f"ft{r['frame_type']}-{r['CRC_width']}")
def test_original_independent_bytes_recover_without_changing_reference(row):
    path = ROOT / f"ft{row['frame_type']}-crc{row['CRC_width']}-input.npz"
    assert hashlib.sha256(path.read_bytes()).hexdigest() == row["input_sha256"]
    z = np.load(path)
    p = profile(row["frame_type"], row["CRC_width"])
    expected = bytes.fromhex(row["expected_payload"])
    assert z["payload"].tobytes() == expected
    direct = decode_psk_frame(z["symbols"], p)
    assert direct["status"] == "valid" and direct["payload"] == expected
    assert direct["header"]["data_length"] == row["raw_header_length"]
    assert direct["payload_length_bytes"] == len(expected)
    assert direct["frame_end_symbol"] == row["actual_frame_end"]
    assert direct["header_crc"] is True and direct["data_crc"] is True
    rng = np.random.default_rng(181391)
    patterns = [(len(z["iq"]),), (1, 32, 257), tuple(rng.integers(1, 514, 37))]
    previous = None
    for chunks in patterns:
        packets, events, rx = receive(p, z["iq"], z["quiet"], chunks)
        assert packets == [expected]
        assert len(events) == 1 and events[0]["frame"]["status"] == "valid"
        assert rx.phy.capture_stats["header_crc_ok"] == 1
        assert rx.phy.capture_stats["data_crc_ok"] == 1
        assert rx.phy._active is None
        # Predefined: same canonical Python operations, exact chunk identity.
        trace = events[0]["symbol_centers_raw"]
        if previous is not None:
            np.testing.assert_array_equal(trace, previous)
        previous = trace


def b1_header_wire(p, raw_length, *, mcs=8, bad_crc=False):
    cfg = p.config
    raw = ControlInfoB1(0, 0, 0, mcs, raw_length, 0, 0).pack(cfg.head_llid)
    if bad_crc:
        raw[-1] ^= 1
    sync = p.sync_symbols()
    control = independent_wire(encode_head(raw, cfg), "BPSK" if cfg.frame_type == 4 else "QPSK",
                               len(sync), 4, False)
    return np.r_[sync, control], raw


@pytest.mark.parametrize("ft", [3, 4])
@pytest.mark.parametrize("width", [24, 32])
def test_zero_length_no_data_crc_no_fake_MAC_and_control_pilot_consumed(ft, width):
    p = profile(ft, width)
    symbols, raw = b1_header_wire(p, 0)
    missing = decode_psk_frame(symbols[:-1], p)
    assert missing["header_crc"] is True and missing["status"] == "truncated_data"
    row = decode_psk_frame(symbols, p)
    assert row["status"] == "valid_empty_control" and row["header_crc"] is True
    assert row["length_ok"] is True and row["data_crc_present"] is False
    assert row["data_crc"] is None and row["payload"] is None
    assert row["frame_end_symbol"] == len(symbols) and row["coded_bits"] == 0
    assert row["data_symbols"] == row["wire_data_symbols"] == 0
    # Actual empty TX has only sync and all specified control pilots; no CRC payload.
    iq = mac_to_iq(b"", p.config)
    npre = 48 if ft == 3 else 64
    assert len(iq) == (npre + len(symbols)) * 4
    np.testing.assert_array_equal(iq, tx_chain(raw, np.empty(0, np.uint8), p.config,
                                              data_present=False))
    pre = np.exp(1j * np.tile([np.pi / 4, 0], npre // 2))
    x, _, _ = audit.reference(np.r_[pre, symbols], .37, 0)
    packets, events, _ = receive(p, x, np.zeros(1024, complex), (7, 31, 67))
    assert packets == []
    assert [e["frame"]["status"] for e in events] == ["valid_empty_control"]


@pytest.mark.parametrize("width", [24, 32])
def test_bad_header_invalid_lengths_context_and_truncation_do_not_decode_data(width, monkeypatch):
    import nearlink_sdr.phy.rx_pipeline as pipeline
    p = profile(3, width)
    monkeypatch.setattr(pipeline, "decode_payload",
                        lambda *a, **k: pytest.fail("untrusted payload"))
    for size in range(1, width // 8):
        symbols, _ = b1_header_wire(p, size)
        row = decode_psk_frame(symbols, p)
        assert row["status"] == "invalid_length" and row["length_ok"] is False
        assert row["header_crc"] is True and row["data_crc"] is None
        assert "frame_end_symbol" not in row
    symbols, _ = b1_header_wire(p, 39)
    assert decode_psk_frame(symbols[:80], p)["status"] == "truncated_header"
    assert decode_psk_frame(symbols, p)["status"] == "truncated_data"
    assert decode_psk_frame(symbols, replace(p, max_payload_bytes=34))["status"] == "invalid_length"
    assert decode_psk_frame(symbols, replace(p, config=replace(p.config, head_llid=7)))[
        "status"] == "bad_header_crc"
    bad, _ = b1_header_wire(p, 2047, bad_crc=True)
    assert decode_psk_frame(bad, p)["status"] == "bad_header_crc"
    retransmit, _ = b1_header_wire(p, 1, mcs=15)
    assert decode_psk_frame(retransmit, p)["status"] == "unsupported_mcs"


@pytest.mark.parametrize("ft", [3, 4])
def test_MAC_transmission_cannot_emit_payload_only_B1_length(ft, monkeypatch):
    import nearlink_sdr.phy.mac_interface as mac
    cfg = profile(ft).config
    observed = []
    def tx(head, data, config, **options):
        observed.append((ControlInfoB1.unpack(head, config.head_llid), data.copy(), options))
        return np.empty(0, complex)
    monkeypatch.setattr(mac, "tx_chain", tx)
    payload = b"independent payload"
    mac_to_iq(payload, cfg)
    assert observed[0][0].data_length == len(payload) + 3
    assert observed[0][2] == {"data_present": True}
    np.testing.assert_array_equal(observed[0][1], np.unpackbits(np.frombuffer(payload, np.uint8)))
    for ctrl in (ControlInfoB1(0, 0, 0, 8, len(payload), 0, 0),
                 ControlInfoB1(0, 0, 0, 6, len(payload) + 3, 0, 0)):
        with pytest.raises(ValueError, match="length/MCS"):
            mac_to_iq(payload, cfg, ctrl)
    with pytest.raises(ValueError, match="plus data CRC"):
        mac_to_iq(bytes(2045), cfg)
    mac_to_iq(bytes(2044), cfg)
    assert observed[-1][0].data_length == 2047


def test_omit_data_is_explicit_bounded_and_never_crc_success_by_construction():
    p = profile(3)
    _, zero = b1_header_wire(p, 0)
    _, nonzero = b1_header_wire(p, 3)
    with pytest.raises(ValueError, match="boolean"):
        tx_chain(zero, np.empty(0), p.config, data_present=0)
    with pytest.raises(ValueError, match="Only an empty B1"):
        tx_chain(zero, np.ones(8), p.config, data_present=False)
    with pytest.raises(ValueError, match="Only an empty B1"):
        tx_chain(zero, np.empty(0), TxConfig(), data_present=False)
    with pytest.raises(ValueError, match="zero length"):
        tx_chain(nonzero, np.empty(0), p.config, data_present=False)


@pytest.mark.parametrize("width", [24, 32])
def test_crc_only_is_distinct_from_absent_data(width):
    p = profile(3, width)
    symbols, _ = b1_header_wire(p, width // 8)
    # The independent GF(2) state for zero input bits is the unchanged seed.
    crc_bits = np.array([(p.config.crc_seed >> k) & 1 for k in range(width - 1, -1, -1)])
    wire = independent_wire(crc_bits, "QPSK", len(symbols), 8, True)
    row = decode_psk_frame(np.r_[symbols, wire], p)
    assert row["status"] == "valid" and row["payload"] == b""
    assert row["data_crc"] is True and row["data_crc_present"] is True
    assert row["payload_length_bytes"] == 0 and row["coded_bits"] == width


@pytest.mark.parametrize("ft,mcs", [(3, 8), (3, 12), (4, 8), (4, 12)])
@pytest.mark.parametrize("width", [24, 32])
def test_standard_B1_information_limit_uses_maximum_wire_length(ft, mcs, width):
    from tests.test_strict_receive import iq_record, transmitted
    p = profile(ft, width)
    p = replace(p, config=replace(p.config, mcs_index=mcs))
    count = 2047 - width // 8
    old, wanted = transmitted(p, length=count)
    npre = 48 if ft == 3 else 64
    wire = np.r_[np.exp(1j * np.tile([np.pi / 4, 0], npre // 2)), old[40:]]
    x, quiet, _, _ = iq_record(wire, cfo=23000, ppm=100)
    packets, events, _ = receive(p, x, quiet, (997, 17))
    assert packets == [wanted] and len(wanted) == count
    row = events[0]["frame"]
    assert row["header"]["data_length"] == 2047 and row["payload_length_bytes"] == count
    assert row["status"] == "valid" and row["data_crc"] is True
