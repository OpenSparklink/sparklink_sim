"""Freeze guards and independent input context for the serial normalization study."""

import hashlib
import json
import sys

import numpy as np
import pytest
from scripts import model_rank_serial as model


@pytest.mark.parametrize("changed", [None, "policy", "source", "eligibility", "digest", "end"])
def test_no_new_held_generation_before_frozen_eligible_development(tmp_path, monkeypatch, changed):
    out = tmp_path / "held"
    argv = ["model_rank_serial", "--output", str(out), "--split", "validation"]
    if changed is not None:
        frozen = dict(policy=dict(model.POLICY), sources=model.sources())
        if changed == "policy":
            frozen["policy"]["serial_register_cap_bits"] += 1
        if changed == "source":
            frozen["sources"]["src/nearlink_sdr/sim/rank_serial.py"] = "0" * 64
        file = tmp_path / "freeze.json"
        file.write_text(json.dumps(frozen))
        prior = dict(
            development_qualified=changed != "eligibility",
            freeze_SHA256=hashlib.sha256(file.read_bytes()).hexdigest(),
        )
        if changed == "digest":
            prior["freeze_SHA256"] = "0" * 64
        (tmp_path / "model.json").write_text(json.dumps(prior))
        end = {} if changed == "end" else frozen["sources"]
        (tmp_path / "source-bindings-at-end.json").write_text(json.dumps(end))
        argv.extend(["--freeze", str(file)])
    monkeypatch.setattr(sys, "argv", argv)
    monkeypatch.setattr(model, "inputs", lambda *_: pytest.fail("No early held generation"))
    with pytest.raises(ValueError, match="frozen"):
        model.main()
    assert not out.exists()


def test_new_developer_inputs_keep_original_payload_and_profile_context(tmp_path):
    # The new held branch is deliberately never generated by this unit test.
    rows = model.inputs(tmp_path, "development")
    assert len(rows) == 15
    assert {r["config"]["frame_type"] for r in rows} == {2, 3, 4}
    assert {r["config"]["mcs_index"] for r in rows} == {8, 12}
    assert {r["family"] for r in rows} >= {
        "tone",
        "burst",
        "wrong-sync-weak",
        "step",
        "noise",
        "silence",
        "noise-only",
        "tone-only",
        "wrong-sync",
        "bad_head",
        "bad_data",
        "truncated",
    }
    for row in rows:
        file = tmp_path / row["artifact"]
        assert model.sha(file) == row["input_SHA256"]
        with np.load(file) as z:
            assert len(z["iq"])
            if row["legal"]:
                for index, expected in enumerate(row["expected"]):
                    assert z[f"expected{index}"].tobytes() == bytes.fromhex(expected)
                assert len(row["expected"]) == row["legal_packets"]
    assert all(model.payload(257, i) != model.payload(257, j) for i in range(3) for j in range(i))


@pytest.mark.parametrize("fault", ["word_loss", "query_drop", "query_expiry", "register_cap"])
def test_adoption_does_not_hide_resource_or_register_failure(fault):
    rows = []
    for ft in [2, 3, 4]:
        for mode in ["pipeline", "serial2"]:
            row = dict(
                frame_type=ft,
                clock_MHz=200,
                blocked=False,
                lanes=model.POLICY["preferred_lanes"][str(ft)],
                normalization=mode,
                word_stream_pass=True,
                statistics=dict(query_dropped=0, query_expired=0, query_completed=7),
                cost=dict(normalization=dict(research_register_cap_pass=True)),
                source_discard_controller=dict(composed_logical_bits=100000),
            )
            rows.append(row)
    assert model.qualify(rows)
    candidate = rows[-1]
    if fault == "word_loss":
        candidate["word_stream_pass"] = False
    elif fault == "query_drop":
        candidate["statistics"]["query_dropped"] = 1
    elif fault == "query_expiry":
        candidate["statistics"]["query_expired"] = 1
    else:
        candidate["cost"]["normalization"]["research_register_cap_pass"] = False
    assert not model.qualify(rows)
